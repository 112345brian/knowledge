"""Port for the stored subjects: look a name up, create a subject, place it in the hierarchy, claim an alias.

The decisions (defaults, which alias may be claimed, which name an entry means) are `subject_rules`; this is only
what they are applied through. An adapter may raise `subject_rules.AliasRefused` from `add_alias` when its own
constraints say no (the SQLite adapter's triggers do), and nothing else is part of the contract.
"""
from typing import Dict, Optional, Protocol

from subject_rules import HierarchyTally


class SubjectRepository(Protocol):
    def find_subject(self, name) -> Optional[int]: ...
    def find_alias(self, alias) -> Optional[int]: ...
    def subject_ids(self) -> Dict[str, int]: ...
    def alias_owners(self) -> Dict[str, str]: ...
    def create_subject(self, name, domain=None) -> int: ...
    def ensure_subject(self, name, domain) -> None: ...
    def place(self, subject_id, parent_id, relation, description, deprecated) -> None: ...
    def replace_with(self, subject_id, replacement_id) -> None: ...
    def add_alias(self, subject_id, alias) -> None: ...
    def tally(self) -> HierarchyTally: ...
