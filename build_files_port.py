"""Port for the file-system and process-level work of a database rebuild: reading the schema, loading step
modules, making the temporary build file, the atomic swap, the backups. `build` decides the order; the adapter
(`local_buildfiles`) owns the disk."""
from typing import Any, ContextManager, List, Protocol


class BuildFiles(Protocol):
    def read_text(self, path) -> str: ...
    def load_module(self, path) -> Any: ...
    def create_exclusive(self, path) -> None: ...
    def remove_if_exists(self, path) -> None: ...
    def makedirs(self, path) -> None: ...
    def exists(self, path) -> bool: ...
    def replace(self, source, target) -> None: ...
    def copy(self, source, target) -> None: ...
    def listdir(self, path) -> List[str]: ...
    def remove(self, path) -> None: ...
    def size(self, path) -> int: ...
    def open_database(self, path) -> Any: ...
    def system_temp_dir(self) -> str: ...
    def temporary_directory(self) -> ContextManager[str]: ...
    def unique_token(self) -> str: ...
