"""Port for the data a build step loads from the private data files and the table writers that belong with them.

Each method is one thing a step used to import a store module for: read a data file into validated values, or
write a prepared set of values into the build database it was given. The adapter (`local_stores`) is the stores;
a step knows none of them, so a test can hand a step a fake world and a step imports no infrastructure at all.
"""
from typing import Any, Optional, Protocol

from build_repositories_port import PrivacyRepository, RevisionRepository, UnitOfWork
from fact_ingest_port import FactRevisionWriter, FactStore
from subject_repository_port import SubjectRepository


class StepStores(Protocol):
    def load_privacy_rules(self, path) -> Any: ...
    def apply_privacy_rules(self, con, rules) -> Any: ...
    def read_entities(self, path) -> Optional[list]: ...
    def link_entities(self, con, entities) -> dict: ...
    def read_subjects(self, path) -> Optional[list]: ...
    def subject_repository(self, con) -> SubjectRepository: ...
    def insert_claim(self, cur, claim) -> int: ...
    def link_claim_premise(self, cur, claim_id, premise) -> int: ...
    def source_repository(self, con) -> Any: ...   # a `build_repositories_port.SourceRepository` over the build connection
    def fact_repository(self, con) -> FactStore: ...
    def revision_writer(self, con) -> FactRevisionWriter: ...
    def unit_of_work(self, con) -> UnitOfWork: ...
    def revision_repository(self, con) -> RevisionRepository: ...
    def privacy_repository(self, con) -> PrivacyRepository: ...
    def entity_link_table(self, con) -> Any: ...
