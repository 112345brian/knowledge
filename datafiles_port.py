"""Port for the data files a maintenance tool reads and rewrites: locked, atomic, byte-exact. The adapter
(`local_datafiles`) owns the file system and the inter-process lock; a tool's core takes a `DataFiles` and does
no I/O of its own."""
from typing import Any, ContextManager, List, Protocol


class DataFiles(Protocol):
    def exists(self, path) -> bool: ...
    def read_text(self, path, encoding="utf-8", newline=None) -> str: ...
    def write_text(self, path, text, encoding="utf-8", newline=None) -> None: ...
    def write_text_atomic(self, path, text) -> None: ...
    def read_array(self, path) -> list: ...
    def load_entries(self, data_dir) -> List[dict]: ...
    def locked(self, path) -> ContextManager[Any]: ...
