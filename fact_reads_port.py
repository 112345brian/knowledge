"""Port for reading the built knowledge.db: what `knowledge.py search|facts|show|subjects|history|audit-*|build-info`
need, without a connection in sight. The adapter opens and closes its own read-only connection per call and
returns plain dicts; nothing here prints or exits."""
from typing import Any, List, Optional, Protocol, Tuple


class DatabaseNotFound(FileNotFoundError):
    """knowledge.db doesn't exist yet (it is built, never hand-created)."""


class FactQueryError(Exception):
    """A read failed: bad full-text syntax, or a db built with an older schema. The message is safe to show."""


class FactReads(Protocol):
    def search_facts(self, terms, subject=None, trust=None, personal=None, limit=20, status=None, include_pending=False,
                     kind=None, valid_at=None, entity=None, identifier=None) -> List[dict]: ...
    def list_facts(self, subject=None, trust=None, status=None, personal=None, limit=50, include_pending=False,
                   kind=None, valid_at=None, entity=None, identifier=None) -> List[dict]: ...
    def get_fact(self, fact_id) -> Optional[dict]: ...
    def list_subjects(self, include_pending=False) -> List[dict]: ...
    def fact_as_of(self, fact_id, as_of) -> Tuple[str, Optional[dict]]: ...
    def get_history(self, ref) -> List[dict]: ...
    def list_pending(self) -> List[dict]: ...
    def source_ids(self, citekey) -> Optional[dict]: ...
    def audit_claims(self) -> Tuple[List[dict], List[dict]]: ...
    def audit_sources(self) -> Tuple[List[dict], List[dict]]: ...
    def audit_source_status(self) -> Tuple[List[dict], List[dict]]: ...
    def latest_build_info(self, db_path=None) -> Optional[dict]: ...
    def compare_build_info(self, other, mine) -> List[dict]: ...
    def subject_context(self) -> Optional[Tuple[dict, set]]: ...
    def existing_db_path(self) -> Optional[str]: ...
    def default_db_path(self) -> Any: ...
