"""Port for reading the built knowledge.db: what `knowledge.py search|facts|show|subjects|history|audit-*|build-info`
need, without a connection in sight. The adapter opens and closes its own read-only connection per call and
returns plain dicts; nothing here prints or exits."""
from typing import Any, List, Optional, Protocol, Tuple


class DatabaseNotFound(FileNotFoundError):
    """knowledge.db doesn't exist yet (it is built, never hand-created)."""


class FactQueryError(Exception):
    """A read failed: bad full-text syntax, or a db built with an older schema. The message is safe to show."""


class FactReads(Protocol):
    """Every read names the database it reads: the caller owns where it lives."""
    def search_facts(self, db_path, terms, subject=None, trust=None, personal=None, limit=20, status=None,
                     include_pending=False, kind=None, valid_at=None, entity=None, identifier=None) -> List[dict]: ...
    def list_facts(self, db_path, subject=None, trust=None, status=None, personal=None, limit=50, include_pending=False,
                   kind=None, valid_at=None, entity=None, identifier=None) -> List[dict]: ...
    def get_fact(self, db_path, fact_id) -> Optional[dict]: ...
    def list_subjects(self, db_path, include_pending=False) -> List[dict]: ...
    def fact_as_of(self, db_path, fact_id, as_of) -> Tuple[str, Optional[dict]]: ...
    def get_history(self, db_path, ref) -> List[dict]: ...
    def list_pending(self, db_path) -> List[dict]: ...
    def source_ids(self, db_path, citekey) -> Optional[dict]: ...
    def audit_claims(self, db_path, today) -> Tuple[List[dict], List[dict]]: ...
    def audit_sources(self, db_path, vault) -> Tuple[List[dict], List[dict]]: ...
    def audit_source_status(self, db_path) -> Tuple[List[dict], List[dict]]: ...
    def latest_build_info(self, db_path) -> Optional[dict]: ...
    def compare_build_info(self, a, b) -> List[dict]: ...
    def subject_context(self, db_path, data_path) -> Optional[Tuple[dict, set]]: ...
    def existing_db_path(self, db_path) -> Optional[str]: ...
