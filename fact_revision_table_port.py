"""Ports for applying the revision log to a built database: reading the log, and the facts / history rows.

The methods are what the use case means (the original entries, a fact's new current state, history raised to
private), not queries. An adapter binds one database connection; it makes no decision.
"""
from typing import Any, Dict, List, Mapping, Protocol, Tuple


class RevisionLogReader(Protocol):
    def read_log(self, path, base=None) -> List[Tuple[int, dict]]: ...


class FactRevisionTable(Protocol):
    def fact_ids_by_source_key(self) -> Dict[str, int]: ...
    def original_revisions(self) -> Dict[str, Dict[str, Any]]: ...
    def record_revision(self, fact_id, revision: Mapping) -> None: ...
    def write_current_state(self, fact_id, state: Mapping) -> None: ...
    def visibility_by_fact(self) -> Dict[int, str]: ...
    def raise_history_to_private(self, fact_ids) -> None: ...
    def revision_count(self) -> int: ...
    def commit(self) -> None: ...
